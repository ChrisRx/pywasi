CMAKE_TOOLCHAIN = """\
# Generated by toolchain/pywasi_build.py for scikit-build-core builds.
# Linux, as far as CMake is concerned, so that MODULE libraries (Python
# extensions) are linked with -shared, which toolchain/wasi-cc turns into
# relocatable objects.
set(CMAKE_SYSTEM_NAME Linux)
set(CMAKE_SYSTEM_PROCESSOR wasm32)
set(CMAKE_C_COMPILER {tc}/wasi-cc)
set(CMAKE_CXX_COMPILER {tc}/wasi-c++)
set(CMAKE_AR {sdk}/bin/llvm-ar)
set(CMAKE_RANLIB {sdk}/bin/llvm-ranlib)
set(CMAKE_CROSSCOMPILING_EMULATOR {tc}/wasi-run)
set(CMAKE_FIND_ROOT_PATH {sysroot} {dist})
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
# Build tools' CMake packages (nanobind, pybind11) are in the build venv,
# C libraries' (Arrow's) in the sysroot.
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE BOTH)
list(APPEND CMAKE_PREFIX_PATH {sysroot})
# Nothing is dynamically linked, and wasm has no RPATH to rewrite.
set(CMAKE_SKIP_RPATH ON)
"""


def cmake_settings(target: Target, work: Path, recipe: dict, site: Path) -> list[str]:
    """scikit-build-core settings that build for the target."""
    toolchain = work / "wasm32-wasip1.cmake"
    toolchain.write_text(
        CMAKE_TOOLCHAIN.format(
            tc=TOOLCHAIN, sdk=os.environ["WASI_SDK_PATH"], sysroot=os.environ.get("PYWASI_SYSROOT", ""), dist=BASE,
        )
    )
    include = BASE / "include" / f"python{target.py_version}"
    defines = {
        "CMAKE_TOOLCHAIN_FILE": toolchain,
        # FindPython would ask the (native) build interpreter.
        "Python_INCLUDE_DIR": include,
        "Python3_INCLUDE_DIR": include,
        "Python_SOABI": target.ext_suffix.split(".")[1],
    }
    if recipe.get("numpy-headers"):
        numpy = site / "numpy" / "_core" / "include"
        defines["Python_NumPy_INCLUDE_DIR"] = defines["Python3_NumPy_INCLUDE_DIR"] = numpy
    # Stripping an installed module would take the symbol table a
    # relocatable object needs.
    return ["install.strip=false"] + [f"cmake.define.{k}={v}" for k, v in defines.items()]


def cross_env(target: Target, work: Path) -> dict:
    """Environment that makes a native CPython build extensions for the target.

    The build backend runs on the native interpreter (same version), with
    sysconfig swapped for the target's so EXT_SUFFIX, compiler settings and
    platform come from the wasm build. The compiler is toolchain/wasi-cc,
    and target headers are put first on the include path, ahead of the
    native ones setuptools would otherwise add.
    """
    sdk = os.environ["WASI_SDK_PATH"]
    sysconfig_dir = work / "sysconfig"
    sysconfig_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy(target.stdlib / f"{target.sysconfigdata}.py", sysconfig_dir)
    include = BASE / "include" / f"python{target.py_version}"
    # C libraries built for WASI (nix/c-libs.nix), e.g. libyaml.
    sysroot = os.environ.get("PYWASI_SYSROOT", "")
    cflags = f"-I{include}" + (f" -I{sysroot}/include" if sysroot else "")
    # Sockets, terminals and libffi as CPython has them, implemented by
    # pywasi's support code in every interpreter's final link.
    support = TOOLCHAIN / "support"
    cflags += f" -I{support / 'include'} -I{support / 'termios'} -I{support / 'ffi'}"
    cc = str(TOOLCHAIN / "wasi-cc")
    cxx = str(TOOLCHAIN / "wasi-c++")
    env = dict(os.environ)
    env.update(
        _PYTHON_SYSCONFIGDATA_NAME=target.sysconfigdata,
        _PYTHON_HOST_PLATFORM="wasi-wasm32",
        PYTHONPATH=str(sysconfig_dir),
        CC=cc,
        CXX=cxx,
        LDSHARED=f"{cc} -shared",
        LDCXXSHARED=f"{cxx} -shared",
        AR=f"{sdk}/bin/llvm-ar",
        CFLAGS=cflags,
        CXXFLAGS=cflags,
        CPPFLAGS=cflags,
        # Only the WASI Python and C libraries (e.g. lxml finds libxml2 this way).
        PKG_CONFIG=str(TOOLCHAIN / "wasi-pkg-config"),
    )
    if sysroot:
        env["LDFLAGS"] = f"-L{sysroot}/lib"
    return env


PYO3_CONFIG = """\
implementation=CPython
version={version}
shared=false
abi3=false
pointer_width=32
build_flags=
suppress_build_script_link_lines=true
ext_suffix={ext_suffix}
"""


def rust_env(target: Target, work: Path) -> dict:
    """Environment for maturin or setuptools-rust to build PyO3 extensions
    for the target.

    cargo builds for wasm32-wasip1 and links each extension with
    toolchain/wasi-rust-ld, which makes the same relocatable object as
    wasi-cc does for C. PyO3 gets the target interpreter's configuration
    from a file (and links nothing itself, like any extension here), and
    maturin reads the target's sysconfig for the wheel's file names.
    """
    config = work / "pyo3-config.txt"
    config.write_text(PYO3_CONFIG.format(version=target.py_version, ext_suffix=target.ext_suffix))
    cc = str(TOOLCHAIN / "wasi-cc")
    return {
        "MATURIN_PEP517_ARGS": "--target wasm32-wasip1",
        "CARGO_BUILD_TARGET": "wasm32-wasip1",
        "CARGO_TARGET_WASM32_WASIP1_LINKER": str(TOOLCHAIN / "wasi-rust-ld"),
        "CARGO_TARGET_DIR": str(work / "target"),
        "PYO3_CONFIG_FILE": str(config),
        "PYO3_CROSS_LIB_DIR": str(target.stdlib),
        "PYO3_CROSS_PYTHON_VERSION": target.py_version,
        # C code in crates (the cc crate), for the target only.
        "CC_wasm32_wasip1": cc,
        "CXX_wasm32_wasip1": str(TOOLCHAIN / "wasi-c++"),
        "AR_wasm32_wasip1": f"{os.environ['WASI_SDK_PATH']}/bin/llvm-ar",
    }


def unpack_sdist(archive: Path, dest: Path) -> Path:
    dest.mkdir(parents=True)
    if archive.name.endswith(".zip"):
        with zipfile.ZipFile(archive) as z:
            z.extractall(dest)
    else:
        with tarfile.open(archive) as t:
            t.extractall(dest, filter="data")
    (src,) = [p for p in dest.iterdir() if p.is_dir()]
    return src


NUMPY_SHIM = """\
# Generated by toolchain/pywasi_build.py: numpy for build scripts running
# on python.wasm, which can't import the real one (its extensions aren't
# linked in). Only the headers are needed, and they must be the wasm
# build's, since _numpyconfig.h records type sizes.
def get_include():
    return {include!r}
"""


def build_shims(recipe: dict, site: Path, work: Path) -> Path | None:
    """Modules for the wasm side of a build (toolchain/wasi-python), or None."""
    if not recipe.get("numpy-headers"):
        return None
    include = site / "numpy" / "_core" / "include"
    if not (include / "numpy" / "_numpyconfig.h").exists():
        raise BuildError("numpy-headers: build numpy first (add it to the requirements)")
    shims = work / "target-shims"
    (shims / "numpy").mkdir(parents=True)
    (shims / "numpy" / "__init__.py").write_text(NUMPY_SHIM.format(include=str(include)))
    # And for meson's dependency('numpy'), which asks pkg-config before the
    # (native) numpy-config.
    version = re.search(r"^version\s*=\s*['\"]([^'\"]+)", (site / "numpy" / "version.py").read_text(), re.M).group(1)
    (shims / "pkgconfig").mkdir()
    (shims / "pkgconfig" / "numpy.pc").write_text(
        f"includedir={include}\n\nName: numpy\nDescription: numpy for wasm32-wasip1\nVersion: {version}\nCflags: -I${{includedir}}\n"
    )
    return shims


def build_from_source(pkg: Package, src_archive: Path | None, target: Target, recipe: dict, site: Path) -> Path:
    numpy_config = site / "numpy" / "_core" / "include" / "numpy" / "_numpyconfig.h"
    key = hashlib.sha256(
        json.dumps(
            [
                pkg.name, pkg.version, recipe, TOOLCHAIN_REV, target.ext_suffix, os.environ.get("PYWASI_SYSROOT"),
                # The compiler and linker wrappers, so changing them rebuilds.
                [(TOOLCHAIN / t).read_text() for t in TOOLCHAIN_SCRIPTS],
                [(TOOLCHAIN / "patches" / p).read_text() for p in recipe.get("patches", [])],
                # The numpy built against (numpy-headers).
                numpy_config.read_text() if recipe.get("numpy-headers") and numpy_config.exists() else None,
            ],
            sort_keys=True,
        ).encode()
    ).hexdigest()[:16]
    out = CACHE / "wheels" / f"{pkg.name}-{pkg.version}-{key}"
    if pkg.local is None and out.exists() and (wheels := list(out.glob("*.whl"))):
        log(f"{pkg.name} {pkg.version}: using cached build {out.name}")
        return wheels[0]

    work = Path(tempfile.mkdtemp(prefix=f"{pkg.name}-", dir=ROOT / "build"))
    try:
        src = pkg.local if pkg.local else unpack_sdist(src_archive, work / "src")
        if pkg.local is None:
            for patch in recipe.get("patches", []):
                run(["patch", "-p1", "--forward", "-d", src, "-i", TOOLCHAIN / "patches" / patch])
        pyproject = tomllib.loads((src / "pyproject.toml").read_text()) if (src / "pyproject.toml").exists() else {}
        build_system = pyproject.get(
            "build-system", {"requires": ["setuptools>=40.8.0"], "build-backend": "setuptools.build_meta:__legacy__"}
        )
        backend = build_system.get("build-backend", "setuptools.build_meta:__legacy__")
        requires = build_system.get("requires", [])

        venv = work / "venv"
        run(["uv", "venv", "--quiet", venv])
        python = venv / "bin" / "python"
        run(["uv", "pip", "install", "--quiet", "--python", python, "build", "wheel", *requires, *recipe.get("build-requires", [])])

        settings = []
        if backend.startswith("mesonpy"):
            cross = work / "wasm32-wasip1.ini"
            cross.write_text(CROSS_FILE.format(tc=TOOLCHAIN, sdk=os.environ["WASI_SDK_PATH"]))
            settings.append(f"setup-args=--cross-file={cross}")
        elif any("scikit-build-core" in r or "scikit_build_core" in r for r in requires + [backend]):
            settings += cmake_settings(target, work, recipe, site)
        for k, v in recipe.get("config-settings", {}).items():
            for item in v if isinstance(v, list) else [v]:
                settings.append(f"{k}={item}")

        env = cross_env(target, work)
        if any(any(b in r for b in RUST_BUILDERS) for r in requires + [backend]):
            env.update(rust_env(target, work))
            # The extension's module, for when a crate has several (PyO3
            # exports a PyInit_* per #[pymodule]), see toolchain/wasi-rust-ld.
            if module := pyproject.get("tool", {}).get("maturin", {}).get("module-name"):
                env["PYWASI_PYO3_MODULE"] = module.rsplit(".", 1)[-1]
        # Build tools installed in the venv (cython, ninja) run natively,
        # some from manylinux wheels that need libstdc++.
        env["PATH"] = f"{venv / 'bin'}{os.pathsep}{env['PATH']}"
        if native := os.environ.get("PYWASI_NATIVE_LIBS"):
            env["LD_LIBRARY_PATH"] = os.pathsep.join(filter(None, [native, env.get("LD_LIBRARY_PATH")]))
        env.update(recipe.get("env", {}))
        if extra := recipe.get("cflags"):
            for var in ("CFLAGS", "CXXFLAGS"):
                env[var] = f"{env[var]} {extra}"
        # Its pure-Python build tools, for scripts run on python.wasm.
        (env["PYWASI_BUILD_SITE"],) = map(str, venv.glob("lib/python3*/site-packages"))
        if shims := build_shims(recipe, site, work):
            env["PYWASI_TARGET_PYTHONPATH"] = str(shims)
            env["PYWASI_PKG_CONFIG_PATH"] = str(shims / "pkgconfig")
        wheel_dir = work / "dist"
        cmd = [python, "-m", "build", "--wheel", "--no-isolation", "--skip-dependency-check", "--outdir", wheel_dir]
        for s in settings:
            cmd.append(f"-C{s}")
        cmd.append(src)
        run(cmd, env=env)

        (whl,) = wheel_dir.glob("*.whl")
        out.mkdir(parents=True, exist_ok=True)
        return Path(shutil.copy(whl, out))
    finally:
        shutil.rmtree(work, ignore_errors=True)


