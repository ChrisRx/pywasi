def c_string(text: str) -> str:
    """A C array initializer holding text, NUL-terminated."""
    data = text.encode() + b"\0"
    rows = [", ".join(str(c) for c in data[i : i + 24]) for i in range(0, len(data), 24)]
    return "{\n    " + ",\n    ".join(rows) + "\n}"


def write_snapshot_header(path: Path):
    """The snapshot module's source, embedded by toolchain/support/pywasi_main.c."""
    snapshot_py = (TOOLCHAIN / "support" / "pywasi_snapshot.py").read_text()
    path.write_text(
        "/* Generated by toolchain/pywasi_build.py. */\n"
        f"static const char pywasi_snapshot_py[] = {c_string(snapshot_py)};\n"
    )


def write_registration(path: Path, modules, entries):
    """C for an object that registers modules with pywasi_main at startup.

    Each name is a module's full dotted name, and each entry the unique
    pywasi_init_* symbol toolchain/wasi-cc gave it.
    """
    decls = "".join(f"extern void *{e}(void);\n" for e in entries)
    calls = "".join(f'    pywasi_register("{name}", {e});\n' for (name, _), e in zip(modules, entries))
    path.write_text(
        "/* Generated by toolchain/pywasi_build.py. */\n"
        "extern void pywasi_register(const char *name, void *(*init)(void));\n"
        f"{decls}\n"
        "__attribute__((constructor)) static void pywasi_register_modules(void) {\n"
        f"{calls}}}\n"
    )


@dataclass
class Module:
    name: str  # full dotted name, e.g. "numpy._core._multiarray_umath"
    entry: str  # its unique pywasi_init_* symbol (toolchain/wasi-cc)
    obj: Path  # relocatable object
    path: str  # where the extension was, relative to site-packages


@dataclass
class Library:
    obj: Path  # relocatable object, with a global pywasi_lib_init_* (toolchain/wasi-cc)
    path: str  # where the library was, relative to site-packages


@dataclass
class Linked:
    modules: list[Module]
    libraries: list[Library]
    args: list[str]  # the wasm-ld command line, without the program name
    cwd: Path  # relative paths in args are relative to this
    out: Path
    inputs: list[Path]  # package objects in args: modules and registration


def link(site: Path, out_wasm: Path, target: Target, excludes: list[str], work: Path) -> Linked:
    """Link every extension object in site into python.wasm, then remove them."""
    sdk = Path(os.environ["WASI_SDK_PATH"])
    cc = TOOLCHAIN / "wasi-cc"
    work.mkdir(parents=True, exist_ok=True)
    exclude = re.compile("|".join(f"(?:{e})" for e in excludes)) if excludes else None

    found_modules = []
    paths = {p for suffix in (target.ext_suffix, ".abi3.so") for p in site.rglob(f"*{suffix}")}
    for path in sorted(paths):
        name = str(path.relative_to(site).parent / path.name.split(".", 1)[0]).replace("/", ".")
        if exclude and exclude.search(name):
            path.unlink()
            continue
        found_modules.append((name, path))

    # toolchain/wasi-cc gave each extension one global symbol, a unique
    # pywasi_init_* entry point wrapping its PyInit_<leaf>.
    modules = []
    for name, path in found_modules:
        syms = subprocess.run(
            [sdk / "bin" / "llvm-nm", "--defined-only", "--extern-only", path],
            check=True,
            capture_output=True,
            text=True,
        ).stdout.split()
        found = [s for s in syms if s.startswith("pywasi_init_")]
        if len(found) != 1:
            raise BuildError(f"{name}: expected one pywasi_init_* symbol in {path} (built without toolchain/wasi-cc?)")
        obj = work / f"{found[0]}.o"
        rel = str(path.relative_to(site))
        shutil.move(path, obj)
        modules.append(Module(name, found[0], obj, rel))
    libraries = take_libraries(site, work)

    write_snapshot_header(work / "pywasi_snapshot_py.h")
    registration = compile_registration(work / "registration", modules)
    srcdir = target.cpython_build.parent.parent
    run(
        [
            cc, "-O2", f"-I{srcdir / 'Include'}", f"-I{target.cpython_build}", f"-I{work}",
            "-c", TOOLCHAIN / "support" / "pywasi_main.c", "-o", work / "pywasi_main.o",
        ]
    )
    run(
        [
            cc, "-O2", f"-I{TOOLCHAIN / 'support' / 'include'}",
            "-c", TOOLCHAIN / "support" / "pywasi_socket.c", "-o", work / "pywasi_socket.o",
        ]
    )
    run([cc, "-O2", "-c", TOOLCHAIN / "support" / "numpy_fpstatus.c", "-o", work / "numpy_fpstatus.o"])
    # Terminals: CPython's termios module, which configure leaves out for
    # WASI, built against pywasi_term.c's <termios.h>. Neither changes the
    # kit's ABI (abi_id), so bundles keep linking.
    term_include = TOOLCHAIN / "support" / "termios"
    run([cc, "-O2", f"-I{term_include}", "-c", TOOLCHAIN / "support" / "pywasi_term.c", "-o", work / "pywasi_term.o"])
    run(
        [
            cc, "-O2", f"-I{term_include}", f"-I{srcdir / 'Include'}", f"-I{target.cpython_build}",
            "-c", srcdir / "Modules" / "termios.c", "-o", work / "termios.o",
        ]
    )
    # mmap, likewise left out by configure, on wasi-libc's emulation (the
    # link already has -lwasi-emulated-mman).
    run(
        [
            cc, "-O2", "-D_WASI_EMULATED_MMAN", f"-I{srcdir / 'Include'}", f"-I{srcdir / 'Include' / 'internal'}",
            f"-I{target.cpython_build}", "-c", srcdir / "Modules" / "mmapmodule.c", "-o", work / "mmapmodule.o",
        ]
    )
    run([cc, "-O2", "-c", TOOLCHAIN / "support" / "pywasi_mmap.c", "-o", work / "pywasi_mmap.o"])
    run([cc, "-O2", "-c", TOOLCHAIN / "support" / "pywasi_posix.c", "-o", work / "pywasi_posix.o"])
    # ctypes, likewise, on pywasi_ffi.c's libffi (no foreign calls beyond
    # simple signatures, no callbacks).
    ffi = TOOLCHAIN / "support" / "ffi"
    ctypes_objs = [work / "pywasi_ffi.o"]
    run([cc, "-O2", f"-I{ffi}", "-c", TOOLCHAIN / "support" / "pywasi_ffi.c", "-o", ctypes_objs[0]])
    for src in ("_ctypes", "callbacks", "callproc", "stgdict", "cfield"):
        obj = work / f"ctypes_{src}.o"
        run(
            [
                cc, "-O2", f"-I{ffi}", f"-I{srcdir / 'Include'}", f"-I{srcdir / 'Include' / 'internal'}",
                f"-I{target.cpython_build}", "-DHAVE_FFI_PREP_CIF_VAR=1", "-DHAVE_FFI_PREP_CLOSURE_LOC=1",
                "-DHAVE_FFI_CLOSURE_ALLOC=1", "-c", srcdir / "Modules" / "_ctypes" / f"{src}.c", "-o", obj,
            ]
        )
        ctypes_objs.append(obj)

    # Reuse CPython's own link line, swapping in our main, adding the
    # extensions, and linking with clang++ for libc++.
    dry = subprocess.run(
        ["make", "-s", "-n", "-W", "Programs/python.o", "python.wasm"],
        cwd=target.cpython_build,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    (line,) = [l for l in dry.splitlines() if "-o python.wasm" in l]
    argv = line.split()
    cmd = [str(sdk / "bin" / "clang++")]
    for a in argv[1:]:
        if a == "python.wasm":
            cmd.append(str(out_wasm))
        elif a == "Programs/python.o":
            cmd.append(str(work / "pywasi_main.o"))
        elif a.endswith("/pywasi_socket_stub.o"):
            # Sockets through pywasi's host functions, see build-python.sh.
            cmd.append(str(work / "pywasi_socket.o"))
        else:
            cmd.append(a)
    if str(work / "pywasi_socket.o") not in cmd:
        raise BuildError("CPython was built without toolchain/support/pywasi_socket.c; rerun scripts/build-python.sh")
    # Libraries first: copies of inline code they share with the modules
    # (a COMDAT group each) are then theirs, which their own code expects.
    inputs = [l.obj for l in libraries] + [m.obj for m in modules] + [registration]
    # numpy formats and parses long double, which wasi-libc leaves out by default.
    cmd += [str(o) for o in inputs] + [str(work / "numpy_fpstatus.o")]
    cmd += [str(work / "pywasi_term.o"), str(work / "termios.o"), "-lc-printscan-long-double"]
    cmd += [str(work / "pywasi_mmap.o"), str(work / "mmapmodule.o"), str(work / "pywasi_posix.o")]
    cmd += [str(o) for o in ctypes_objs]
    # wasi-libc emulation of mmap etc., used by C libraries such as OpenBLAS.
    cmd += ["-lwasi-emulated-mman", "-lwasi-emulated-signal", "-lwasi-emulated-process-clocks", "-lwasi-emulated-getpid"]
    # C++ exceptions and setjmp/longjmp (toolchain/wasi-cc): libc++ built
    # with exceptions, and the unwinder and setjmp runtime they need.
    cmd += ["-fwasm-exceptions", "-lunwind", "-lsetjmp"]
    # DWARF is most of the file and only helps debuggers. The name section
    # stays, so traps still show function names.
    cmd += ["-Wl,--strip-debug"]

    # Run wasm-ld directly with the command clang++ would, so a link kit
    # (--kit) records exactly what was run here.
    dry = subprocess.run(cmd + ["-###"], cwd=target.cpython_build, capture_output=True, text=True)
    if dry.returncode != 0:
        raise BuildError(f"link: {dry.stderr.strip()}")
    dry = dry.stderr
    (ld_line,) = [l for l in dry.splitlines() if re.search(r'wasm-ld"? ', l)]
    ld_argv = shlex.split(ld_line)
    out_wasm.parent.mkdir(parents=True, exist_ok=True)
    log(f"linking {len(modules)} extension modules into {out_wasm}")
    subprocess.run(ld_argv, cwd=target.cpython_build, check=True, stdout=sys.stderr)
    return Linked(
        modules=modules, libraries=libraries, args=ld_argv[1:], cwd=target.cpython_build, out=out_wasm, inputs=inputs
    )


def take_libraries(site: Path, work: Path) -> list[Library]:
    """Move packages' own shared libraries (lib*.so* objects with a
    pywasi_lib_init_* symbol, from toolchain/wasi-cc) out of site, and the
    symbolic links to them."""
    sdk = Path(os.environ["WASI_SDK_PATH"])
    libraries = []
    links = []
    for path in sorted(site.rglob("lib*.so*")):
        if path.is_symlink():
            links.append(path)
            continue
        if not path.is_file() or path.name.endswith(".pywasi-archives"):
            continue
        syms = subprocess.run(
            [sdk / "bin" / "llvm-nm", "--defined-only", "--extern-only", path],
            capture_output=True,
            text=True,
        ).stdout.split()
        found = [s for s in syms if s.startswith("pywasi_lib_init_")]
        if not found:
            continue
        obj = work / f"{found[0]}.o"
        # Wheels can't hold symbolic links, so libfoo.so.1 and libfoo.so
        # are copies.
        if any(l.obj == obj for l in libraries):
            path.unlink()
            continue
        rel = str(path.relative_to(site))
        shutil.move(path, obj)
        libraries.append(Library(obj, rel))
    for link in links:
        if not link.exists():
            link.unlink()
    for path in site.rglob("*.pywasi-archives"):
        path.unlink()
    return libraries


def compile_registration(stem: Path, modules: list[Module]) -> Path:
    write_registration(stem.with_suffix(".c"), [(m.name, None) for m in modules], [m.entry for m in modules])
    obj = stem.with_suffix(".o")
    run([TOOLCHAIN / "wasi-cc", "-O2", "-c", stem.with_suffix(".c"), "-o", obj])
    return obj


