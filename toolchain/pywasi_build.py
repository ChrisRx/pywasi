def env_project(requirements: list[str], preload: list[str]) -> Path:
    """A generated uv project for an ad-hoc dependency list.

    Lives under build/cache/envs/<hash of the inputs>, so the same list maps
    to the same lock and interpreter. Unpinned names resolve to the newest
    version on first use and then stay locked.
    """
    reqs = sorted({str(Requirement(r)) for r in requirements})
    # The base CPython build and the C libraries too, so changing either
    # rebuilds every set.
    base = hashlib.sha256((BASE / "bin" / "python.wasm").read_bytes()).hexdigest() if (BASE / "bin" / "python.wasm").exists() else ""
    sysroot = os.environ.get("PYWASI_SYSROOT", "")
    key = hashlib.sha256(json.dumps([reqs, preload, TOOLCHAIN_REV, LAYOUT_REV, base, sysroot]).encode()).hexdigest()[:16]
    project = CACHE / "envs" / key
    if (project / "uv.lock").exists():
        return project
    project.mkdir(parents=True, exist_ok=True)
    deps = "".join(f"    {json.dumps(r)},\n" for r in reqs)
    (project / "pyproject.toml").write_text(
        "# Generated by toolchain/pywasi_build.py --with.\n"
        "[project]\n"
        'name = "pywasi-env"\n'
        'version = "0"\n'
        f'requires-python = ">={sys.version_info.major}.{sys.version_info.minor}"\n'
        f"dependencies = [\n{deps}]\n\n"
        "[tool.pywasi]\n"
        f"preload = {json.dumps(preload)}\n"
    )
    run(["uv", "lock", "--quiet"], cwd=project)
    return project


def main():
    ap = argparse.ArgumentParser(
        description="Build a WASI Python for a uv project, or for a list of requirements (--with)."
    )
    ap.add_argument("project", type=Path, nargs="?", help="directory with pyproject.toml and uv.lock")
    ap.add_argument("-o", "--out", type=Path, help="output directory (default: PROJECT/.pywasi)")
    ap.add_argument("--no-snapshot", action="store_true", help="skip Wizer pre-initialization")
    ap.add_argument(
        "--with", dest="requirements", action="append", default=[], metavar="REQ",
        help="build for this requirement instead of a project, e.g. numpy or pyyaml==6.0.3 (repeatable)",
    )
    ap.add_argument(
        "--preload", action="append", default=[], metavar="MODULE",
        help="module to import into the snapshot, with --with (repeatable)",
    )
    ap.add_argument(
        "--archive", type=Path, metavar="FILE",
        help="also pack the interpreter into FILE (.tar.zst) and write FILE.sha256",
    )
    ap.add_argument(
        "--kit", type=Path, metavar="FILE",
        help="also write a link kit (.tar.zst) for linking interpreters from Go",
    )
    ap.add_argument(
        "--bundles", type=Path, metavar="DIR",
        help="also write a bundle (.tar.zst) for each package built from source into DIR",
    )
    ap.add_argument(
        "--env", action="store_true",
        help="build for the --with requirements, which may be none (standard library only)",
    )
    args = ap.parse_args()

    if args.requirements or args.env:
        if args.project:
            ap.error("give a project or --with/--env, not both")
        project = env_project(args.requirements, args.preload)
        if args.out is None and not (args.kit or args.bundles) and (project / ".pywasi" / "bin" / "python.wasm").exists():
            log(f"up to date: {project / '.pywasi'}")
            # Pure Python, so refreshing it doesn't need a rebuild.
            for lib in (project / ".pywasi" / "lib").glob("python3.*"):
                install_support(lib)
            finish(project / ".pywasi", args.archive)
            return
    elif args.project:
        project = args.project.resolve()
    else:
        ap.error("give a project directory, --with or --env")

    out = (args.out or project / ".pywasi").resolve()
    target = probe_target()
    settings = tomllib.loads((project / "pyproject.toml").read_text()).get("tool", {}).get("pywasi", {})
    recipes = load_recipes(project)
    packages = resolve(project, target)
    staging = Path(tempfile.mkdtemp(prefix="pywasi-", dir=ROOT / "build"))
    try:
        site = staging / "site-packages"
        site.mkdir()
        excludes = []
        built = {}  # name -> (Package, its installed files)
        for pkg in packages:
            recipe = recipes.get(pkg.name, {})
            if "exclude-extensions" in recipe:
                excludes.append(recipe["exclude-extensions"])
            wheel = None if pkg.local else pure_wheel(pkg, target)
            if wheel:
                log(f"{pkg.name} {pkg.version}: pure wheel")
                install_wheel(fetch(wheel["url"], wheel["hash"]), site)
                continue
            if pkg.local is None and pkg.sdist is None:
                raise BuildError(f"{pkg.name} {pkg.version}: no pure wheel and no sdist in uv.lock")
            log(f"{pkg.name} {pkg.version}: from source")
            archive = None if pkg.local else fetch(pkg.sdist["url"], pkg.sdist["hash"])
            files = staging / "packages" / pkg.name
            install_wheel(build_from_source(pkg, archive, target, recipe), files)
            shutil.copytree(files, site, dirs_exist_ok=True)
            built[pkg.name] = (pkg, files)

        linked = link(site, staging / "python.wasm", target, excludes, staging / "link")
        names = [m.name for m in linked.modules]

        if out.exists():
            shutil.rmtree(out)
        (out / "bin").mkdir(parents=True)
        shutil.copy(staging / "python.wasm", out / "bin" / "python.wasm")
        lib = out / "lib" / target.stdlib.name
        shutil.copytree(target.stdlib, lib, ignore=STDLIB_IGNORE)
        install_support(lib)
        shutil.copytree(site, lib / "site-packages")
        scrub_paths(lib)
        compile_bytecode(lib, out)

        abi = abi_id(linked, target)
        if args.kit:
            write_kit(linked, lib, target, abi, args.kit.resolve())
        if args.bundles:
            for pkg, files in built.values():
                if pkg.local is None:
                    write_bundle(pkg, files, linked, target, abi, args.bundles.resolve())
    finally:
        shutil.rmtree(staging, ignore_errors=True)

    preload = settings.get("preload", [])
    snapshotted = settings.get("snapshot", True) and not args.no_snapshot
    # Describes the interpreter for pywasi (and people).
    manifest = {
        "python": target.markers["python_full_version"],
        "packages": [{"name": p.name, "version": p.version} for p in packages if p.local is None],
        "extensions": names,
        "preload": preload if snapshotted else [],
        "snapshot": snapshotted,
    }
    (out / "pywasi.json").write_text(json.dumps(manifest, indent=2) + "\n")

    if snapshotted:
        # _pywasi (Go Eval/Call) is always ready in the snapshot.
        snapshot(out, ["_pywasi", *preload])

    size = (out / "bin" / "python.wasm").stat().st_size / 2**20
    log(f"done: {out} ({len(packages)} packages, {len(names)} extensions, python.wasm {size:.0f} MiB)")
    finish(out, args.archive)


# Link kits and bundles: linking interpreters from Go (pywasi's linker.go)


def abi_id(linked: Linked, target: Target) -> str:
    """Identifies what extension objects must be built against.

    Bundles only link with a kit of the same id: the same CPython build and
    toolchain.
    """
    # CPython's own objects (it links them directly, without a libpython).
    inputs = {str(p) for p in linked.inputs}
    h = hashlib.sha256()
    for arg in linked.args:
        path = linked.cwd / arg
        if arg not in inputs and not arg.startswith("-") and not Path(arg).is_absolute() and path.is_file():
            h.update(arg.encode() + b"\0" + hashlib.sha256(path.read_bytes()).digest())
    h.update(json.dumps([TOOLCHAIN_REV, target.ext_suffix, os.environ.get("WASI_SDK_PATH", "")]).encode())
    return h.hexdigest()[:16]


def strip_debug(*paths: Path):
    """Remove debug sections from objects and archives: they record build
    paths, and the link strips them from python.wasm anyway (--strip-debug)."""
    if paths:
        run([Path(os.environ["WASI_SDK_PATH"]) / "bin" / "llvm-strip", "--strip-debug", *paths])


def write_kit(linked: Linked, lib: Path, target: Target, abi: str, archive: Path):
    """Everything to link python.wasm except package objects, as a .tar.zst:

        link.json   {"abi", "python", "args"}: the wasm-ld command line, with
                    "{output}" for the output file and "{inputs}" where
                    package objects (modules and registrations) go
        link/       every file the command reads, at /kit/link/... in args
        lib/        the standard library, as in an interpreter home
    """
    stage = Path(tempfile.mkdtemp(prefix="pywasi-kit-", dir=ROOT / "build"))
    try:
        (stage / "link").mkdir()
        placed = {}

        def place(path: Path) -> str:
            key = str(path.resolve())
            if key not in placed:
                name = f"{len(placed):03d}-{path.name}"
                shutil.copy(path, stage / "link" / name)
                placed[key] = f"/kit/link/{name}"
            return placed[key]

        inputs = {str(p) for p in linked.inputs}
        search, args, inputs_placed = [], [], False
        it = iter(linked.args)
        for a in it:
            if a == "-o":
                next(it)
                args += ["-o", "{output}"]
            elif a in inputs:
                if not inputs_placed:
                    args.append("{inputs}")
                    inputs_placed = True
            elif a.startswith("-L"):
                search.append(linked.cwd / a[2:])
            elif a.startswith("-l"):
                found = [d / f"lib{a[2:]}.a" for d in search if (d / f"lib{a[2:]}.a").exists()]
                if not found:
                    raise BuildError(f"kit: no library for {a}")
                args.append(place(found[0]))
            elif not a.startswith("-") and (linked.cwd / a).is_file():
                args.append(place(linked.cwd / a))
            else:
                args.append(a)
        if not inputs_placed:
            raise BuildError("kit: package objects not found in the link command")
        strip_debug(*(f for f in (stage / "link").iterdir() if f.suffix in (".o", ".a")))
        link_json = {"version": 1, "abi": abi, "python": target.markers["python_full_version"], "args": args}
        (stage / "link.json").write_text(json.dumps(link_json, indent=2) + "\n")
        shutil.copytree(lib, stage / "lib" / lib.name, ignore=shutil.ignore_patterns("site-packages"))
        digest = write_archive(stage, archive)
        log(f"kit: {archive} ({archive.stat().st_size / 2**20:.1f} MiB, abi {abi}, sha256:{digest})")
    finally:
        shutil.rmtree(stage, ignore_errors=True)


def write_bundle(pkg: Package, files: Path, linked: Linked, target: Target, abi: str, outdir: Path):
    """A package built from source, for linking from Go, as a .tar.zst:

        bundle.json     {"name", "version", "abi", "python", "requires",
                         "modules": [{"name", "object"}]}
        objects/        one relocatable object per extension module
        registration.o  registers the modules with pywasi_main
        site/           the package's Python files, without extensions
    """
    owned = {str(p.relative_to(files)) for p in files.rglob("*") if p.is_file()}
    modules = [m for m in linked.modules if m.path in owned]
    stage = Path(tempfile.mkdtemp(prefix=f"pywasi-bundle-{pkg.name}-", dir=ROOT / "build"))
    try:
        (stage / "objects").mkdir()
        for m in modules:
            shutil.copy(m.obj, stage / "objects" / m.obj.name)
        strip_debug(*(stage / "objects").iterdir())
        compile_registration(stage / "registration", modules)
        (stage / "registration.c").unlink()
        suffixes = (target.ext_suffix, ".abi3.so")
        shutil.copytree(files, stage / "site", ignore=lambda d, names: [n for n in names if n.endswith(suffixes)])
        scrub_paths(stage / "site")
        compile_bytecode(stage / "site", stage / "site", "/site")
        requires = []
        for meta in (stage / "site").glob("*.dist-info/METADATA"):
            requires = email.parser.Parser().parsestr(meta.read_text(), headersonly=True).get_all("Requires-Dist") or []
        bundle_json = {
            "version": 1,
            "name": pkg.name,
            "package_version": pkg.version,
            "abi": abi,
            "python": target.markers["python_full_version"],
            "requires": requires,
            "modules": [{"name": m.name, "object": f"objects/{m.obj.name}"} for m in modules],
        }
        (stage / "bundle.json").write_text(json.dumps(bundle_json, indent=2) + "\n")
        outdir.mkdir(parents=True, exist_ok=True)
        archive = outdir / f"{pkg.name}-{pkg.version}-py{target.py_version}.tar.zst"
        digest = write_archive(stage, archive)
        log(f"bundle: {archive} ({len(modules)} modules, {archive.stat().st_size / 2**20:.1f} MiB, sha256:{digest})")
    finally:
        shutil.rmtree(stage, ignore_errors=True)


def finish(home: Path, archive: Path | None):
    if archive:
        archive = archive.resolve()
        digest = write_archive(home, archive)
        log(f"archive: {archive} ({archive.stat().st_size / 2**20:.1f} MiB, sha256:{digest})")
    # The interpreter home, for callers (e.g. the Go build package).
    print(home)


if __name__ == "__main__":
    try:
        main()
    except (BuildError, subprocess.CalledProcessError) as e:
        log(f"error: {e}")
        sys.exit(1)
