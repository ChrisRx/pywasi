def scrub_paths(tree: Path):
    """Replace this checkout's path with /pywasi in Python and JSON files.

    CPython's sysconfig data and some packages' build info (numpy's
    __config__.py) record build-time paths, which would make outputs depend
    on where the checkout is and leak it. Nothing at runtime uses them.
    """
    old, new = str(ROOT).encode(), b"/pywasi"
    for path in tree.rglob("*"):
        if path.suffix in (".py", ".json") and path.is_file():
            data = path.read_bytes()
            if old in data:
                path.write_bytes(data.replace(old, new))


def compile_bytecode(lib: Path, root: Path, guest: str = "/"):
    """Precompile lib to .pyc (one optimization level).

    Imports outside the snapshot read these instead of compiling every run
    (several times faster). Hash-based "unchecked" pycs don't depend on file
    timestamps, which archives reset, and are never rewritten.

    Each .pyc records its source path: the path under root, placed at guest
    (where it is at runtime), so the build directory doesn't end up in the
    bytecode and the same sources always give the same files. Python fixes
    the path up to the real location on import anyway.
    """
    for cache in lib.rglob("__pycache__"):
        shutil.rmtree(cache)
    run(
        [
            TOOLCHAIN / "wasi-python", "-m", "compileall", "-q", "-o", "0",
            "--invalidation-mode", "unchecked-hash", "-s", root, "-p", guest, lib,
        ]
    )


def write_archive(home: Path, archive: Path):
    """Pack home into a reproducible .tar.zst and return its sha256.

    Entries are sorted with fixed owners, modes and times, so the same home
    always gives the same digest.
    """
    def clean(info: tarfile.TarInfo):
        info.uid = info.gid = 0
        info.uname = info.gname = ""
        info.mtime = 0
        info.mode = 0o755 if info.isdir() or info.mode & 0o111 else 0o644
        return info

    paths = sorted(p for p in home.rglob("*") if not p.is_symlink())
    archive.parent.mkdir(parents=True, exist_ok=True)
    tmp = archive.with_name(archive.name + ".part")
    with tarfile.open(tmp, "w:zst", level=19, format=tarfile.PAX_FORMAT) as tar:
        for path in paths:
            tar.add(path, arcname=path.relative_to(home).as_posix(), recursive=False, filter=clean)
    tmp.replace(archive)
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    archive.with_name(archive.name + ".sha256").write_text(f"{digest}  {archive.name}\n")
    return digest


def install_support(lib: Path):
    """Ship the _pywasi module (request/response for Go Eval and Call), and
    sitecustomize, which patches packages that assume threads."""
    shutil.copy(TOOLCHAIN / "support" / "_pywasi.py", lib / "_pywasi.py")
    shutil.copy(TOOLCHAIN / "support" / "sitecustomize.py", lib / "sitecustomize.py")


def host_stub() -> Path:
    """A module with pywasi's host functions, all failing, for
    running a linked interpreter outside pywasi: wasmtime --preload
    pywasi=PATH. Built once into build/."""
    out = ROOT / "build" / "pywasi-host-stub.wasm"
    src = TOOLCHAIN / "support" / "pywasi_host_stub.c"
    if not out.exists() or out.stat().st_mtime < src.stat().st_mtime:
        sdk = Path(os.environ["WASI_SDK_PATH"])
        run([sdk / "bin" / "clang", "--target=wasm32", "-nostdlib", "-O2", "-Wl,--no-entry", src, "-o", out])
    return out


def install_data(home: Path):
    """Ship the data files C libraries and the stdlib look for at fixed
    paths (home is mounted at the guest root):

    - CA certificates where OpenSSL looks for them (OPENSSLDIR is /etc/ssl),
      so ssl can verify servers. SSL_CERT_FILE overrides them.
    - The time zone database where zoneinfo looks for it (--with-tzpath in
      scripts/build-python.sh), without the posix/ and right/ copies.
    """
    certs = home / "etc" / "ssl" / "cert.pem"
    certs.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy(os.environ["PYWASI_CACERT"], certs)
    certs.chmod(0o644)
    zoneinfo = home / "share" / "zoneinfo"
    if zoneinfo.exists():
        shutil.rmtree(zoneinfo)
    shutil.copytree(
        os.environ["PYWASI_ZONEINFO"],
        zoneinfo,
        ignore=shutil.ignore_patterns("posix", "right"),
        copy_function=shutil.copyfile,
    )
    # copytree keeps the Nix store's read-only directory modes.
    for d in [zoneinfo, *(p for p in zoneinfo.rglob("*") if p.is_dir())]:
        d.chmod(0o755)


def snapshot(home: Path, preload: list[str]):
    """Pre-initialize home/bin/python.wasm in place with Wizer.

    The interpreter is started (and preload modules imported) once at build
    time with home mounted at the guest root, exactly as at runtime, and the
    resulting memory becomes the module's initial state.
    """
    wasm = home / "bin" / "python.wasm"
    tmp = wasm.with_suffix(".snapshot.wasm")
    log(f"snapshotting interpreter (preload: {', '.join(preload) or 'none'})")
    # A throwaway /tmp, as runs have one (pywasi.WithTempDir), so modules
    # that look for a temp directory while preloading (tempfile caches its
    # choice) find it there.
    scratch = Path(tempfile.mkdtemp(prefix="pywasi-snapshot-", dir=ROOT / "build"))
    try:
        snapshot_with(home, wasm, tmp, preload, scratch)
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    tmp.replace(wasm)


def snapshot_with(home: Path, wasm: Path, out: Path, preload: list[str], scratch: Path):
    run(
        [
            "wasmtime", "wizer",
            "-W", "exceptions=y",
            # WASI is available to the init function (filesystem, env, clocks).
            "-S", "cli=y",
            "-W", "max-wasm-stack=16777216",
            "--dir", f"{home}::/",
            "--dir", f"{scratch}::/tmp",
            "--env", "PYTHONHOME=/",
            "--env", "PYTHONDONTWRITEBYTECODE=1",
            "--env", f"PYWASI_PRELOAD={','.join(preload)}",
            "--rename-func", "_start=pywasi-resume",
            # pywasi's host functions, failing (sockets aren't used here).
            "--preload", f"pywasi={host_stub()}",
            "-o", out, wasm,
        ],
        stdout=subprocess.DEVNULL,
    )


