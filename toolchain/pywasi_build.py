"""Build a self-contained WASI Python for a uv project.

Reads the project's uv.lock (via `uv export`), evaluates environment
markers against the wasm interpreter, and assembles:

    OUT/bin/python.wasm            CPython with every C extension linked in
    OUT/lib/python3.X/...          stdlib + site-packages

Pure-Python packages are installed from py3-none-any wheels in the lock.
Packages with C extensions are built from their sdist with the project's
own PEP 517 backend, cross-compiled through toolchain/wasi-cc, and then
statically linked into python.wasm as built-in modules.

Run inside `nix develop` after scripts/build-python.sh:

    uv run --script toolchain/pywasi_build.py examples/numpy-app
    uv run --script toolchain/pywasi_build.py --with numpy --with pyyaml==6.0.3
    uv run --script toolchain/pywasi_build.py --env    # standard library only

The interpreter's directory is printed on stdout when done. With
--archive FILE it is also packed into a reproducible .tar.zst for
pywasi.WithArchive (see scripts/publish.sh).
"""

