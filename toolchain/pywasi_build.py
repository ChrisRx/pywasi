class BuildError(Exception):
    pass


def log(msg):
    print(f"pywasi: {msg}", file=sys.stderr, flush=True)


def run(cmd, **kw):
    log("$ " + " ".join(str(c) for c in cmd))
    # stdout is reserved for the result (the interpreter path).
    kw.setdefault("stdout", sys.stderr)
    subprocess.run([str(c) for c in cmd], check=True, **kw)


# Target interpreter


@dataclass
class Target:
    py_version: str  # "3.14"
    ext_suffix: str  # ".cpython-314-wasm32-wasi.so"
    sysconfigdata: str  # "_sysconfigdata__wasi_wasm32-wasi"
    markers: dict
    stdlib: Path  # BASE/lib/python3.14
    cpython_build: Path  # cross-build/wasm32-wasip1 (for the final link)


TARGET_PROBE = r"""
import json, os, platform, sys, sysconfig
v = sys.implementation.version
impl_version = f"{v.major}.{v.minor}.{v.micro}"
if v.releaselevel != "final":
    impl_version += v.releaselevel[0] + str(v.serial)
print(json.dumps({
    "ext_suffix": sysconfig.get_config_var("EXT_SUFFIX"),
    "sysconfigdata": sysconfig._get_sysconfigdata_name(),
    "srcdir": sysconfig.get_config_var("abs_srcdir"),
    "markers": {
        "implementation_name": sys.implementation.name,
        "implementation_version": impl_version,
        "os_name": os.name,
        "platform_machine": platform.machine(),
        "platform_release": platform.release(),
        "platform_system": platform.system(),
        "platform_version": platform.version(),
        "python_full_version": platform.python_version(),
        "platform_python_implementation": platform.python_implementation(),
        "python_version": ".".join(platform.python_version_tuple()[:2]),
        "sys_platform": sys.platform,
    },
}))
"""


def probe_target() -> Target:
    if not (BASE / "bin" / "python.wasm").exists():
        raise BuildError("dist/python not found; run scripts/build-python.sh first")
    out = subprocess.run(
        [TOOLCHAIN / "wasi-python", "-c", TARGET_PROBE],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    info = json.loads(out)
    py_version = info["markers"]["python_version"]
    build = Path(info["srcdir"]) / "cross-build" / "wasm32-wasip1"
    if not (build / "Makefile").exists():
        raise BuildError(f"CPython WASI build tree not found at {build}")
    return Target(
        py_version=py_version,
        ext_suffix=info["ext_suffix"],
        sysconfigdata=info["sysconfigdata"],
        markers=info["markers"],
        stdlib=BASE / "lib" / f"python{py_version}",
        cpython_build=build,
    )


# Lockfile


@dataclass
class Package:
    name: str
    version: str
    wheels: list = field(default_factory=list)  # [{url, hash}]
    sdist: dict | None = None
    local: Path | None = None  # path source (the project itself)


def resolve(project: Path, target: Target) -> list[Package]:
    """Packages needed on the target, pinned by uv.lock."""
    if not (project / "uv.lock").exists():
        raise BuildError(f"{project}/uv.lock not found; run `uv lock`")
    exported = subprocess.run(
        [
            "uv", "export", "--frozen", "--no-dev", "--no-hashes", "--no-header",
            "--no-annotate", "--no-emit-project", "--format", "requirements-txt",
        ],
        cwd=project,
        check=True,
        capture_output=True,
        text=True,
    ).stdout

    with open(project / "uv.lock", "rb") as f:
        lock = tomllib.load(f)
    by_key = {(canonicalize_name(p["name"]), p["version"]): p for p in lock["package"] if "version" in p}

    env = dict(target.markers, extra="")
    packages = []
    for line in exported.splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "-")):
            continue
        req = Requirement(line)
        if req.marker and not req.marker.evaluate(env):
            continue
        spec = next(iter(req.specifier), None)
        if req.url or spec is None or spec.operator != "==":
            raise BuildError(f"only registry packages pinned with == are supported: {line}")
        entry = by_key.get((canonicalize_name(req.name), spec.version))
        if entry is None:
            raise BuildError(f"{req.name}=={spec.version} missing from uv.lock")
        packages.append(
            Package(
                name=canonicalize_name(req.name),
                version=spec.version,
                wheels=entry.get("wheels", []),
                sdist=entry.get("sdist"),
            )
        )

    pyproject = tomllib.loads((project / "pyproject.toml").read_text())
    if "build-system" in pyproject:
        name = canonicalize_name(pyproject["project"]["name"])
        packages.append(Package(name=name, version=pyproject["project"].get("version", "0"), local=project))
    else:
        log("project has no [build-system]; installing dependencies only")
    return packages


def load_recipes(project: Path) -> dict:
    recipes = tomllib.loads((TOOLCHAIN / "recipes.toml").read_text())
    pyproject = tomllib.loads((project / "pyproject.toml").read_text())
    for name, cfg in pyproject.get("tool", {}).get("pywasi", {}).get("packages", {}).items():
        recipes.setdefault(canonicalize_name(name), {}).update(cfg)
    return {canonicalize_name(k): v for k, v in recipes.items()}


# Downloads and wheels


def fetch(url: str, digest: str) -> Path:
    algo, _, expected = digest.partition(":")
    dest = CACHE / "downloads" / expected / url.rsplit("/", 1)[-1]
    if dest.exists():
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    log(f"fetching {url}")
    h = hashlib.new(algo)
    tmp = dest.with_suffix(dest.suffix + ".part")
    with urllib.request.urlopen(url) as resp, open(tmp, "wb") as f:
        while chunk := resp.read(1 << 20):
            h.update(chunk)
            f.write(chunk)
    if h.hexdigest() != expected:
        tmp.unlink()
        raise BuildError(f"hash mismatch for {url}")
    tmp.rename(dest)
    return dest


def pure_wheel(pkg: Package, target: Target) -> dict | None:
    """A wheel that runs anywhere: no ABI, any platform, Python 3."""
    cp = "cp" + target.py_version.replace(".", "")
    for w in pkg.wheels:
        _, _, _, tags = parse_wheel_filename(w["url"].rsplit("/", 1)[-1])
        for t in tags:
            if t.abi == "none" and t.platform == "any" and (t.interpreter in ("py3", cp) or re.fullmatch(r"py3\d*", t.interpreter)):
                return w
    return None


def install_wheel(whl: Path, site: Path):
    with zipfile.ZipFile(whl) as z:
        z.extractall(site)
    # <name>.data/{purelib,platlib} belong in site-packages; scripts, headers
    # and data have nowhere to go in the guest and are dropped.
    for data in site.glob("*.data"):
        for scheme in ("purelib", "platlib"):
            src = data / scheme
            if src.is_dir():
                shutil.copytree(src, site, dirs_exist_ok=True)
        shutil.rmtree(data)


# Building from source


CROSS_FILE = """\
[binaries]
c = '{tc}/wasi-cc'
cpp = '{tc}/wasi-c++'
ar = '{sdk}/bin/llvm-ar'
strip = '{sdk}/bin/llvm-strip'
python = '{tc}/wasi-python'
python3 = '{tc}/wasi-python'
exe_wrapper = '{tc}/wasi-run'
pkg-config = '{tc}/wasi-pkg-config'

[host_machine]
system = 'wasi'
cpu_family = 'wasm32'
cpu = 'wasm32'
endian = 'little'

[properties]
needs_exe_wrapper = true
# wasm32 long double is IEEE binary128.
longdouble_format = 'IEEE_QUAD_LE'
"""


def cross_env(target: Target, work: Path) -> dict:
    """Environment that makes a native CPython build extensions for the target.

    The build backend runs on the native interpreter (same version), with
    sysconfig swapped for the target's so EXT_SUFFIX, compiler settings and
    platform come from the wasm build. The compiler is toolchain/wasi-cc,
    and target headers are put first on the include path, ahead of the
    native ones setuptools would otherwise add.
    """
    sdk = os.environ["WASI_SDK_PATH"]
    sysconfig_dir = work / "sysconfig"
    sysconfig_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy(target.stdlib / f"{target.sysconfigdata}.py", sysconfig_dir)
    include = BASE / "include" / f"python{target.py_version}"
    # C libraries built for WASI (nix/c-libs.nix), e.g. libyaml.
    sysroot = os.environ.get("PYWASI_SYSROOT", "")
    cflags = f"-I{include}" + (f" -I{sysroot}/include" if sysroot else "")
    cc = str(TOOLCHAIN / "wasi-cc")
    cxx = str(TOOLCHAIN / "wasi-c++")
    env = dict(os.environ)
    env.update(
        _PYTHON_SYSCONFIGDATA_NAME=target.sysconfigdata,
        _PYTHON_HOST_PLATFORM="wasi-wasm32",
        PYTHONPATH=str(sysconfig_dir),
        CC=cc,
        CXX=cxx,
        LDSHARED=f"{cc} -shared",
        LDCXXSHARED=f"{cxx} -shared",
        AR=f"{sdk}/bin/llvm-ar",
        CFLAGS=cflags,
        CXXFLAGS=cflags,
        CPPFLAGS=cflags,
    )
    if sysroot:
        env["LDFLAGS"] = f"-L{sysroot}/lib"
    return env


def unpack_sdist(archive: Path, dest: Path) -> Path:
    dest.mkdir(parents=True)
    if archive.name.endswith(".zip"):
        with zipfile.ZipFile(archive) as z:
            z.extractall(dest)
    else:
        with tarfile.open(archive) as t:
            t.extractall(dest, filter="data")
    (src,) = [p for p in dest.iterdir() if p.is_dir()]
    return src


def build_from_source(pkg: Package, src_archive: Path | None, target: Target, recipe: dict) -> Path:
    key = hashlib.sha256(
        json.dumps(
            [
                pkg.name, pkg.version, recipe, TOOLCHAIN_REV, target.ext_suffix, os.environ.get("PYWASI_SYSROOT"),
                [(TOOLCHAIN / "patches" / p).read_text() for p in recipe.get("patches", [])],
            ],
            sort_keys=True,
        ).encode()
    ).hexdigest()[:16]
    out = CACHE / "wheels" / f"{pkg.name}-{pkg.version}-{key}"
    if pkg.local is None and out.exists() and (wheels := list(out.glob("*.whl"))):
        log(f"{pkg.name} {pkg.version}: using cached build {out.name}")
        return wheels[0]

    work = Path(tempfile.mkdtemp(prefix=f"{pkg.name}-", dir=ROOT / "build"))
    try:
        src = pkg.local if pkg.local else unpack_sdist(src_archive, work / "src")
        if pkg.local is None:
            for patch in recipe.get("patches", []):
                run(["patch", "-p1", "--forward", "-d", src, "-i", TOOLCHAIN / "patches" / patch])
        pyproject = tomllib.loads((src / "pyproject.toml").read_text()) if (src / "pyproject.toml").exists() else {}
        build_system = pyproject.get(
            "build-system", {"requires": ["setuptools>=40.8.0"], "build-backend": "setuptools.build_meta:__legacy__"}
        )
        backend = build_system.get("build-backend", "setuptools.build_meta:__legacy__")
        requires = build_system.get("requires", [])
        if any(any(u in r for u in UNSUPPORTED_BACKENDS) for r in requires + [backend]):
            raise BuildError(f"{pkg.name}: Rust extensions are not supported yet ({backend})")

        venv = work / "venv"
        run(["uv", "venv", "--quiet", venv])
        python = venv / "bin" / "python"
        run(["uv", "pip", "install", "--quiet", "--python", python, "build", "wheel", *requires, *recipe.get("build-requires", [])])

        settings = []
        if backend.startswith("mesonpy"):
            cross = work / "wasm32-wasip1.ini"
            cross.write_text(CROSS_FILE.format(tc=TOOLCHAIN, sdk=os.environ["WASI_SDK_PATH"]))
            settings.append(f"setup-args=--cross-file={cross}")
        for k, v in recipe.get("config-settings", {}).items():
            for item in v if isinstance(v, list) else [v]:
                settings.append(f"{k}={item}")

        env = cross_env(target, work)
        # Build tools installed in the venv (cython, ninja) run natively.
        env["PATH"] = f"{venv / 'bin'}{os.pathsep}{env['PATH']}"
        env.update(recipe.get("env", {}))
        wheel_dir = work / "dist"
        cmd = [python, "-m", "build", "--wheel", "--no-isolation", "--skip-dependency-check", "--outdir", wheel_dir]
        for s in settings:
            cmd.append(f"-C{s}")
        cmd.append(src)
        run(cmd, env=env)

        (whl,) = wheel_dir.glob("*.whl")
        out.mkdir(parents=True, exist_ok=True)
        return Path(shutil.copy(whl, out))
    finally:
        shutil.rmtree(work, ignore_errors=True)


# Final link


def c_string(text: str) -> str:
    """A C array initializer holding text, NUL-terminated."""
    data = text.encode() + b"\0"
    rows = [", ".join(str(c) for c in data[i : i + 24]) for i in range(0, len(data), 24)]
    return "{\n    " + ",\n    ".join(rows) + "\n}"


def write_snapshot_header(path: Path):
    """The snapshot module's source, embedded by toolchain/support/pywasi_main.c."""
    snapshot_py = (TOOLCHAIN / "support" / "pywasi_snapshot.py").read_text()
    path.write_text(
        "/* Generated by toolchain/pywasi_build.py. */\n"
        f"static const char pywasi_snapshot_py[] = {c_string(snapshot_py)};\n"
    )


def write_registration(path: Path, modules, entries):
    """C for an object that registers modules with pywasi_main at startup.

    Each name is a module's full dotted name, and each entry the unique
    pywasi_init_* symbol toolchain/wasi-cc gave it.
    """
    decls = "".join(f"extern void *{e}(void);\n" for e in entries)
    calls = "".join(f'    pywasi_register("{name}", {e});\n' for (name, _), e in zip(modules, entries))
    path.write_text(
        "/* Generated by toolchain/pywasi_build.py. */\n"
        "extern void pywasi_register(const char *name, void *(*init)(void));\n"
        f"{decls}\n"
        "__attribute__((constructor)) static void pywasi_register_modules(void) {\n"
        f"{calls}}}\n"
    )


@dataclass
class Module:
    name: str  # full dotted name, e.g. "numpy._core._multiarray_umath"
    entry: str  # its unique pywasi_init_* symbol (toolchain/wasi-cc)
    obj: Path  # relocatable object
    path: str  # where the extension was, relative to site-packages


@dataclass
class Linked:
    modules: list[Module]
    args: list[str]  # the wasm-ld command line, without the program name
    cwd: Path  # relative paths in args are relative to this
    out: Path
    inputs: list[Path]  # package objects in args: modules and registration


def link(site: Path, out_wasm: Path, target: Target, excludes: list[str], work: Path) -> Linked:
    """Link every extension object in site into python.wasm, then remove them."""
    sdk = Path(os.environ["WASI_SDK_PATH"])
    cc = TOOLCHAIN / "wasi-cc"
    work.mkdir(parents=True, exist_ok=True)
    exclude = re.compile("|".join(f"(?:{e})" for e in excludes)) if excludes else None

    found_modules = []
    paths = {p for suffix in (target.ext_suffix, ".abi3.so") for p in site.rglob(f"*{suffix}")}
    for path in sorted(paths):
        name = str(path.relative_to(site).parent / path.name.split(".", 1)[0]).replace("/", ".")
        if exclude and exclude.search(name):
            path.unlink()
            continue
        found_modules.append((name, path))

    # toolchain/wasi-cc gave each extension one global symbol, a unique
    # pywasi_init_* entry point wrapping its PyInit_<leaf>.
    modules = []
    for name, path in found_modules:
        syms = subprocess.run(
            [sdk / "bin" / "llvm-nm", "--defined-only", "--extern-only", path],
            check=True,
            capture_output=True,
            text=True,
        ).stdout.split()
        found = [s for s in syms if s.startswith("pywasi_init_")]
        if len(found) != 1:
            raise BuildError(f"{name}: expected one pywasi_init_* symbol in {path} (built without toolchain/wasi-cc?)")
        obj = work / f"{found[0]}.o"
        rel = str(path.relative_to(site))
        shutil.move(path, obj)
        modules.append(Module(name, found[0], obj, rel))

    write_snapshot_header(work / "pywasi_snapshot_py.h")
    registration = compile_registration(work / "registration", modules)
    srcdir = target.cpython_build.parent.parent
    run(
        [
            cc, "-O2", f"-I{srcdir / 'Include'}", f"-I{target.cpython_build}", f"-I{work}",
            "-c", TOOLCHAIN / "support" / "pywasi_main.c", "-o", work / "pywasi_main.o",
        ]
    )
    run([cc, "-O2", "-c", TOOLCHAIN / "support" / "cxa_abort.c", "-o", work / "cxa_abort.o"])
    run([cc, "-O2", "-c", TOOLCHAIN / "support" / "numpy_fpstatus.c", "-o", work / "numpy_fpstatus.o"])

    # Reuse CPython's own link line, swapping in our main, adding the
    # extensions, and linking with clang++ for libc++.
    dry = subprocess.run(
        ["make", "-s", "-n", "-W", "Programs/python.o", "python.wasm"],
        cwd=target.cpython_build,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    (line,) = [l for l in dry.splitlines() if "-o python.wasm" in l]
    argv = line.split()
    cmd = [str(sdk / "bin" / "clang++")]
    for a in argv[1:]:
        if a == "python.wasm":
            cmd.append(str(out_wasm))
        elif a == "Programs/python.o":
            cmd.append(str(work / "pywasi_main.o"))
        else:
            cmd.append(a)
    inputs = [m.obj for m in modules] + [registration]
    # numpy formats and parses long double, which wasi-libc leaves out by default.
    cmd += [str(o) for o in inputs] + [str(work / "cxa_abort.o"), str(work / "numpy_fpstatus.o"), "-lc-printscan-long-double"]
    # wasi-libc emulation of mmap etc., used by C libraries such as OpenBLAS.
    cmd += ["-lwasi-emulated-mman", "-lwasi-emulated-signal", "-lwasi-emulated-process-clocks"]
    # DWARF is most of the file and only helps debuggers. The name section
    # stays, so traps still show function names.
    cmd += ["-Wl,--strip-debug"]

    # Run wasm-ld directly with the command clang++ would, so a link kit
    # (--kit) records exactly what was run here.
    dry = subprocess.run(cmd + ["-###"], cwd=target.cpython_build, check=True, capture_output=True, text=True).stderr
    (ld_line,) = [l for l in dry.splitlines() if re.search(r'wasm-ld"? ', l)]
    ld_argv = shlex.split(ld_line)
    out_wasm.parent.mkdir(parents=True, exist_ok=True)
    log(f"linking {len(modules)} extension modules into {out_wasm}")
    subprocess.run(ld_argv, cwd=target.cpython_build, check=True, stdout=sys.stderr)
    return Linked(modules=modules, args=ld_argv[1:], cwd=target.cpython_build, out=out_wasm, inputs=inputs)


def compile_registration(stem: Path, modules: list[Module]) -> Path:
    write_registration(stem.with_suffix(".c"), [(m.name, None) for m in modules], [m.entry for m in modules])
    obj = stem.with_suffix(".o")
    run([TOOLCHAIN / "wasi-cc", "-O2", "-c", stem.with_suffix(".c"), "-o", obj])
    return obj


