package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestReadRequirements(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) string {
		t.Helper()
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
		return path
	}
	write("base.txt", "tabulate>=0.9  # tables\n-r requirements.txt\n")
	file := write("requirements.txt", `# Generated by pip-compile
--index-url https://pypi.org/simple

numpy==2.5.5 \
    --hash=sha256:aaaa \
    --hash=sha256:bbbb
pandas[performance]==3.1.1 ; python_version >= "3.11"
-rbase.txt
pkg @ https://example.com/pkg.whl#sha256=cccc
`)
	got, notes, err := readRequirements(file)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"numpy==2.5.5",
		`pandas[performance]==3.1.1 ; python_version >= "3.11"`,
		"tabulate>=0.9",
		"pkg @ https://example.com/pkg.whl#sha256=cccc",
	}
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Errorf("got %q, want %q", got, want)
	}
	if len(notes) != 1 || !strings.Contains(notes[0], "ignoring --index-url") {
		t.Errorf("notes: %q", notes)
	}

	for name, content := range map[string]string{"e.txt": "-e .\n", "c.txt": "-c constraints.txt\n"} {
		if _, _, err := readRequirements(write(name, content)); err == nil {
			t.Errorf("%s: no error", name)
		}
	}
}
